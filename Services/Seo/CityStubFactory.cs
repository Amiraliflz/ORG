namespace Application.Services.Seo;

/// <summary>Safe stub city profiles when hand-authored copy is missing.</summary>
public static class CityStubFactory
{
  public static CityCatalog.CityProfile Create(string nameFa, string slug)
  {
    var (region, role, blurb, tips) = Infer(nameFa);
    return new CityCatalog.CityProfile(
      nameFa,
      slug,
      region,
      role,
      blurb,
      tips,
      NearbyHints(nameFa));
  }

  private static (string Region, string Role, string Blurb, string[] Tips) Infer(string name)
  {
    if (ContainsAny(name, "وان"))
      return (
        "ترکیه",
        "شهر وان در ترکیه",
        $"{name} در کشور ترکیه قرار دارد و یکی از مقاصد ترانزیتی سواری بین‌المللی مسترشوفر در محور ایران–ترکیه است.",
        [
          "برای سفرهای مرزی و ترانزیتی، مدارک و زمان عبور را از قبل هماهنگ کنید.",
          "در ایام پیک، زودتر رزرو کنید."
        ]);

    if (ContainsAny(name, "بندر", "عباس", "بوشهر", "قشم", "کیش", "انزلی", "چابهار"))
      return (
        "نوار ساحلی",
        "مقصد ساحلی و بندری",
        $"{name} در شبکه سواری بین‌شهری مسترشوفر به‌عنوان مبدأ یا مقصد ساحلی/بندری پوشش داده می‌شود.",
        [
          "برای مقصدهای بندری و ساحلی، زمان رسیدن را با ترافیک محلی هماهنگ کنید.",
          "جزئیات محل سوار/پیاده شدن را قبل از حرکت با پشتیبانی هماهنگ کنید."
        ]);

    if (ContainsAny(name, "رشت", "لاهیجان", "چالوس", "نوشهر", "رامسر", "ساری", "گرگان", "آمل", "بابل", "تنکابن", "آستارا", "فومن", "ماسال"))
      return (
        "شمال ایران",
        "مسیر شمالی و گردشگری",
        $"{name} در محور شمال کشور قرار دارد؛ تقاضا در تعطیلات و پایان هفته معمولاً بالاتر است.",
        [
          "در بارندگی و مه شمال، حاشیه زمانی بیشتری بگذارید.",
          "در ایام پیک، زودتر رزرو کنید."
        ]);

    if (ContainsAny(name, "مشهد", "قم", "نیشابور", "سبزوار"))
      return (
        "مسیر زیارتی / شرق",
        "مقصد زیارتی یا اتصال شرقی",
        $"{name} در شبکه سفرهای بین‌شهری مسترشوفر نقش زیارتی یا اتصال شرقی دارد.",
        [
          "در ایام مذهبی و تعطیلات خاص، تقاضا بالا می‌رود؛ زودتر رزرو کنید.",
          "زمان حرکت را با برنامه زیارت یا اقامت هماهنگ کنید."
        ]);

    if (ContainsAny(name, "تبریز", "اردبیل", "زنجان", "ارومیه", "مراغه", "میانه"))
      return (
        "شمال‌غرب",
        "مسیر شمال‌غرب",
        $"{name} روی محور شمال‌غرب قرار دارد و مسیرهای طولانی‌تری نسبت به مرکز دارد.",
        [
          "در زمستان شرایط جوی شمال‌غرب را جدی بگیرید.",
          "برای مسیرهای طولانی، استراحت و حاشیه زمانی در نظر بگیرید."
        ]);

    if (ContainsAny(name, "همدان", "کرمانشاه", "سنندج", "خرم", "بروجرد", "ملایر", "ایلام"))
      return (
        "غرب ایران",
        "مسیر غربی",
        $"{name} در غرب کشور پوشش داده می‌شود و زمان سفر به فصل و شرایط جاده وابسته است.",
        [
          "در زمستان غرب، حاشیه زمانی بیشتری بگذارید.",
          "قبل از حرکت وضعیت جاده را بررسی کنید."
        ]);

    if (ContainsAny(name, "شیراز", "اهواز", "کرمان", "یزد", "بوشهر", "دزفول", "آبادان", "یاسوج"))
      return (
        "جنوب / مرکز–جنوب",
        "مسیر جنوبی یا مرکزی–جنوبی",
        $"{name} در شبکه مسیرهای جنوب و مرکز–جنوب مسترشوفر قرار دارد.",
        [
          "در تابستان، زمان حرکت را با گرمای روز هماهنگ کنید.",
          "در نوروز و تعطیلات طولانی زودتر رزرو کنید."
        ]);

    if (ContainsAny(name, "اصفهان", "کاشان", "شهرکرد", "اراک", "ساوه", "نطنز", "نجف"))
      return (
        "مرکز ایران",
        "مسیر مرکزی",
        $"{name} در محور مرکزی کشور قرار دارد و برای سفر کاری و گردشگری پرتکرار است.",
        [
          "مسیرهای مرکزی معمولاً پایدارتر از جاده‌های کوهستانی شمال‌اند.",
          "در تعطیلات پایان هفته رزرو زودهنگام توصیه می‌شود."
        ]);

    return (
      "ایران",
      "مبدأ/مقصد بین‌شهری",
      $"{name} یکی از شهرهای تحت پوشش سواری بین‌شهری مسترشوفر است؛ مسیرهای فعال از و به این شهر در فهرست زیر آمده‌اند.",
      [
        "تاریخ سفر را از قبل انتخاب کنید تا گزینه‌های همان روز را ببینید.",
        "برای هماهنگی مبدأ و مقصد دقیق، با پشتیبانی تماس بگیرید."
      ]);
  }

  private static string[] NearbyHints(string name) =>
    name == "تهران"
      ? ["شمال", "اصفهان", "غرب"]
      : ["تهران"];

  private static bool ContainsAny(string name, params string[] parts) =>
    parts.Any(p => name.Contains(p, StringComparison.Ordinal));
}
