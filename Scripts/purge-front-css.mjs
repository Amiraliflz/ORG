#!/usr/bin/env node
/**
 * Build a public-page CSS subset from Vuexy core + theme.
 * Booking/admin keep the full files; this is only wired in _StylesFront.cshtml.
 */
import { PurgeCSS } from "purgecss";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = resolve(root, "wwwroot/vendor/css/rtl/core-front.css");

const safelist = {
  standard: [
    "html",
    "body",
    "show",
    "collapse",
    "collapsing",
    "collapsed",
    "fade",
    "active",
    "disabled",
    "open",
    "light-style",
    "layout-navbar-fixed",
    "layout-wide",
    "navbar-active",
    "dropdown-menu-end",
  ],
  greedy: [
    /^col-/,
    /^row/,
    /^g[xy]?-/,
    /^m[trblxyse]?-/,
    /^p[trblxyse]?-/,
    /^d-/,
    /^flex-/,
    /^justify-/,
    /^align-/,
    /^text-/,
    /^bg-/,
    /^border/,
    /^rounded/,
    /^shadow/,
    /^btn/,
    /^nav/,
    /^navbar/,
    /^dropdown/,
    /^accordion/,
    /^card/,
    /^form/,
    /^input/,
    /^badge/,
    /^modal/,
    /^offcanvas/,
    /^container/,
    /^gap-/,
    /^w-/,
    /^h-/,
    /^mh-/,
    /^mw-/,
    /^overflow/,
    /^position/,
    /^top-/,
    /^bottom-/,
    /^end-/,
    /^start-/,
    /^translate/,
    /^fs-/,
    /^fw-/,
    /^lh-/,
    /^link-/,
    /^list-/,
    /^alert/,
    /^spinner/,
    /^placeholder/,
    /^visually/,
    /^ratio/,
    /^sticky/,
    /^fixed/,
    /^zindex/,
    /^z-/,
    /^opacity/,
    /^pe-/,
    /^ps-/,
    /^ms-/,
    /^me-/,
    /^mt-/,
    /^mb-/,
    /^pt-/,
    /^pb-/,
    /^px-/,
    /^py-/,
    /^mx-/,
    /^my-/,
    /^order-/,
    /^offset-/,
    /^col$/,
    /^layout-/,
    /^landing-/,
    /^app-brand/,
    /^menu-/,
    /^section-/,
    /^first-section/,
    /^scaleX/,
    /^ti-/,
    /^waves-/,
    /^bs-/,
    /^data-bs-/,
    /^form-check/,
    /^form-control/,
    /^form-select/,
    /^input-group/,
    /^page-/,
    /^breadcrumb/,
    /^pagination/,
    /^table/,
    /^vr$/,
    /^hstack/,
    /^vstack/,
    /^object-/,
    /^user-select/,
    /^pe-none/,
    /^stretched-link/,
    /^focus-ring/,
    /^icon-/,
    /^avatar/,
    /^divider/,
    /^bg-label/,
    /^text-heading/,
    /^text-body/,
    /^text-muted/,
    /^display-/,
    /^lead$/,
    /^small$/,
    /^h[1-6]$/,
  ],
  keyframes: true,
  variables: true,
};

const result = await new PurgeCSS().purge({
  content: [
    `${root}/Areas/AgencyArea/Views/**/*.cshtml`,
    `${root}/wwwroot/js/front-main.js`,
    `${root}/wwwroot/js/searchpage.js`,
    `${root}/wwwroot/js/IndexPage.js`,
    `${root}/wwwroot/js/Trips.js`,
    `${root}/wwwroot/js/site.js`,
    `${root}/wwwroot/css/*.css`,
  ],
  css: [
    `${root}/wwwroot/vendor/css/rtl/core.css`,
    `${root}/wwwroot/vendor/css/rtl/theme-default.css`,
  ],
  safelist,
  fontFace: true,
  keyframes: true,
  variables: true,
});

const combined = result.map((r) => r.css).join("\n\n");
await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, `/* Purged front CSS — regenerate with: node scripts/purge-front-css.mjs */\n${combined}\n`);
console.log(`Wrote ${outFile} (${(combined.length / 1024).toFixed(1)} KB)`);
